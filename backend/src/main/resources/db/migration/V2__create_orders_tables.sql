-- Tabela de domínio dos status: garante a integridade via FK e permite
-- incluir novos status com um INSERT, sem alterar a estrutura de orders.
CREATE TABLE order_statuses (
    code VARCHAR(20) PRIMARY KEY
);

INSERT INTO order_statuses (code)
VALUES ('RECEBIDO'), ('EM_PREPARO'), ('SAIU_PARA_ENTREGA'), ('ENTREGUE'), ('CANCELADO');

CREATE TABLE orders (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name  VARCHAR(120)             NOT NULL,
    customer_phone VARCHAR(20),

    -- endereço de entrega
    street         VARCHAR(150)             NOT NULL,
    number         VARCHAR(10)              NOT NULL,
    complement     VARCHAR(100),
    neighborhood   VARCHAR(100)             NOT NULL,
    city           VARCHAR(100)             NOT NULL,
    state          VARCHAR(2)               NOT NULL,
    zip_code       VARCHAR(9)               NOT NULL,

    status         VARCHAR(20)              NOT NULL,
    total_amount   NUMERIC(10, 2)           NOT NULL,
    created_by     BIGINT                   NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_orders_status FOREIGN KEY (status) REFERENCES order_statuses (code),
    CONSTRAINT fk_orders_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT ck_orders_total_amount CHECK (total_amount >= 0)
);

CREATE INDEX idx_orders_status ON orders (status);
CREATE INDEX idx_orders_created_at ON orders (created_at);

CREATE TABLE order_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT         NOT NULL,
    product_name VARCHAR(120)   NOT NULL,
    quantity     INTEGER        NOT NULL,
    unit_price   NUMERIC(10, 2) NOT NULL,

    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT ck_order_items_quantity CHECK (quantity > 0),
    CONSTRAINT ck_order_items_unit_price CHECK (unit_price >= 0)
);

CREATE INDEX idx_order_items_order_id ON order_items (order_id);
